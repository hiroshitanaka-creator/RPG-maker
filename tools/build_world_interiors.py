def layout(index: int, room: int, kind: str) -> list[str]:
    cells = [["#" if x in (0, 31) or y in (0, 17) else "." for x in range(32)] for y in range(18)]
    if kind == "dungeon":
        for x in (9, 20):
            gap = 3 + (index * 3 + room * 5 + x) % 11
            for y in range(1, 17):
                if y not in (gap, gap + 1):
                    cells[y][x] = "#"
    else:
        for x, y in [(7, 7), (8, 7), (22, 9), (23, 9), (14, 12)]:
            cells[y][x] = "#"
    # 出入口と各活動地点を結ぶ道を残す。壁の切れ目を探せるよう通路は一列。
    for x, y in [(2, 4), (2, 14), (5, 4), (12, 6), (24, 10), (28, 14)]:
        cells[y][x] = "."
    return ["".join(row) for row in cells]


